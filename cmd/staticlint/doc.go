// Command staticlint запускает набор статических анализаторов проекта.
//
// # Запуск
//
// Проверить все пакеты текущего модуля без предварительной сборки:
//
//	go run ./cmd/staticlint ./...
//
// Собрать отдельный исполняемый файл и использовать его повторно:
//
//	go build -o staticlint ./cmd/staticlint
//	./staticlint ./...
//
// На Windows собранный файл запускается командой staticlint.exe ./....
// Аргументы после имени команды имеют тот же формат, что и у go vet:
// можно передать ./..., отдельный пакет или список пакетов. Общая справка
// доступна с флагом -help, подробная документация конкретной проверки —
// командой staticlint help NAME, например staticlint help SA1000.
// Ненулевой код завершения означает, что анализатор нашёл проблему или
// пакет не удалось загрузить.
//
// # Стандартные анализаторы Go
//
// В multichecker включены следующие проверки из
// golang.org/x/tools/go/analysis/passes:
//
//   - appends — обнаруживает append без переданных добавляемых значений.
//   - asmdecl — сопоставляет объявления Go-функций с assembly-реализациями.
//   - assign — находит бесполезные присваивания переменной самой себе.
//   - atomic — проверяет типичные ошибки при использовании sync/atomic.
//   - bools — ищет подозрительные и избыточные булевы выражения.
//   - buildtag — проверяет корректность и расположение build constraints.
//   - cgocall — проверяет нарушения правил передачи указателей в cgo.
//   - composite — требует ключи полей в composite literals внешних типов.
//   - copylocks — обнаруживает копирование значений, содержащих lock.
//   - defers — ищет распространённые ошибки в defer-выражениях.
//   - directive — проверяет корректность директив компилятора Go.
//   - errorsas — проверяет второй аргумент вызова errors.As.
//   - framepointer — проверяет assembly-код, повреждающий frame pointer.
//   - httpresponse — находит defer resp.Body.Close до проверки ошибки.
//   - ifaceassert — обнаруживает невозможные type assertions интерфейсов.
//   - loopclosure — находит захват переменных цикла замыканиями.
//   - lostcancel — проверяет, что cancel-функции context вызываются.
//   - nilfunc — обнаруживает бессмысленное сравнение функции с nil.
//   - printf — проверяет форматные строки и аргументы Printf-подобных функций.
//   - shift — проверяет сдвиги, равные или превышающие размер целого типа.
//   - sigchanyzer — требует буферизированный канал для os/signal.Notify.
//   - slog — проверяет ключи и значения вызовов log/slog.
//   - stdmethods — проверяет сигнатуры методов известных интерфейсов stdlib.
//   - stdversion — запрещает API новее версии Go, объявленной модулем.
//   - stringintconv — находит подозрительные преобразования integer в string.
//   - structtag — проверяет синтаксис и согласованность тегов структур.
//   - testinggoroutine — запрещает Fatal, FailNow и SkipNow из горутин теста.
//   - tests — проверяет сигнатуры Test, Benchmark, Fuzz и Example.
//   - timeformat — находит ошибочную дату 2006-02-01 в layout времени.
//   - unmarshal — требует передавать указатель в Unmarshal-подобные функции.
//   - unreachable — обнаруживает недостижимый код.
//   - unsafeptr — проверяет недопустимые преобразования unsafe.Pointer.
//   - unusedresult — находит проигнорированные результаты важных функций.
//   - waitgroup — обнаруживает WaitGroup.Add, вызванный внутри новой горутины.
//
// # Анализаторы Staticcheck класса SA
//
// Подключается полный список staticcheck.Analyzers текущей зафиксированной
// версии зависимости. Назначение каждой проверки:
//
//   - SA1000 — некорректное регулярное выражение.
//   - SA1001 — некорректный шаблон text/template или html/template.
//   - SA1002 — некорректный layout в time.Parse.
//   - SA1003 — неподдерживаемый аргумент функции encoding/binary.
//   - SA1004 — подозрительно малая нетипизированная константа в time.Sleep.
//   - SA1005 — некорректный первый аргумент exec.Command.
//   - SA1006 — Printf с динамической строкой формата без аргументов.
//   - SA1007 — некорректный URL в net/url.Parse.
//   - SA1008 — неканонический ключ в http.Header.
//   - SA1010 — FindAll с n == 0, всегда возвращающий пустой результат.
//   - SA1011 — передача некорректного UTF-8 функциям пакета strings.
//   - SA1012 — передача nil вместо context.Context.
//   - SA1013 — перепутанные аргументы io.Seeker.Seek.
//   - SA1014 — передача неуказателя в Unmarshal или Decode.
//   - SA1015 — потенциальная утечка time.Tick.
//   - SA1016 — попытка перехватить неперехватываемый сигнал.
//   - SA1017 — небуферизированный канал для os/signal.Notify.
//   - SA1018 — strings.Replace с n == 0.
//   - SA1019 — использование устаревшего API.
//   - SA1020 — некорректная пара host:port для net.Listen-подобного API.
//   - SA1021 — сравнение net.IP через bytes.Equal.
//   - SA1023 — изменение входного буфера реализацией io.Writer.
//   - SA1024 — повторяющиеся символы в cutset строки.
//   - SA1025 — некорректное использование результата Timer.Reset.
//   - SA1026 — попытка сериализовать канал или функцию.
//   - SA1027 — невыровненный 64-битный атомарный доступ.
//   - SA1028 — вызов sort.Slice не для slice.
//   - SA1029 — неподходящий ключ для context.WithValue.
//   - SA1030 — некорректный аргумент функции strconv.
//   - SA1031 — пересекающиеся byte slices, переданные encoder.
//   - SA1032 — перепутанный порядок аргументов errors.Is.
//   - SA2000 — WaitGroup.Add внутри горутины с риском гонки.
//   - SA2001 — пустая критическая секция из-за немедленного Unlock.
//   - SA2002 — вызов FailNow или SkipNow внутри горутины теста.
//   - SA2003 — defer Lock сразу после Lock вместо defer Unlock.
//   - SA3000 — TestMain не вызывает os.Exit и скрывает ошибки тестов.
//   - SA3001 — присваивание b.N, искажающее результаты benchmark.
//   - SA4000 — одинаковые выражения по обе стороны бинарного оператора.
//   - SA4001 — бессмысленная конструкция &*x.
//   - SA4003 — сравнение unsigned-значения с отрицательным.
//   - SA4004 — цикл, безусловно завершающийся после первой итерации.
//   - SA4005 — незаметное присваивание полю value receiver.
//   - SA4006 — значение переменной перезаписывается до чтения.
//   - SA4008 — переменная условия цикла не изменяется.
//   - SA4009 — аргумент функции перезаписывается до первого чтения.
//   - SA4010 — результат append нигде не используется.
//   - SA4011 — break без эффекта.
//   - SA4012 — сравнение значения с NaN.
//   - SA4013 — двойное отрицание булева значения.
//   - SA4014 — повторяющееся условие в цепочке if/else if.
//   - SA4015 — бессмысленная математическая операция после integer conversion.
//   - SA4016 — бессмысленная битовая операция.
//   - SA4017 — игнорирование результата функции без побочных эффектов.
//   - SA4018 — присваивание переменной самой себе.
//   - SA4019 — повторяющиеся build constraints.
//   - SA4020 — недостижимая ветвь type switch.
//   - SA4021 — append(y) вместо прямого присваивания y.
//   - SA4022 — сравнение адреса переменной с nil.
//   - SA4023 — невозможное сравнение interface с нетипизированным nil.
//   - SA4024 — проверка невозможного результата builtin-функции.
//   - SA4025 — целочисленное деление литералов, всегда дающее ноль.
//   - SA4026 — попытка выразить отрицательный ноль константой Go.
//   - SA4027 — изменение копии, возвращённой URL.Query.
//   - SA4028 — выражение x % 1, всегда равное нулю.
//   - SA4029 — неэффективная попытка сортировки slice.
//   - SA4030 — неэффективная попытка генерации случайного числа.
//   - SA4031 — сравнение заведомо ненулевого значения с nil.
//   - SA4032 — невозможное значение runtime.GOOS или runtime.GOARCH.
//   - SA5000 — присваивание в nil map.
//   - SA5001 — defer Close до проверки ошибки.
//   - SA5002 — пустой бесконечный цикл, блокирующий scheduler.
//   - SA5003 — defer внутри бесконечного цикла.
//   - SA5004 — бесконечный select с пустой default-ветвью.
//   - SA5005 — finalizer удерживает финализируемый объект.
//   - SA5007 — бесконечная рекурсия.
//   - SA5008 — некорректный struct tag.
//   - SA5009 — некорректный вызов Printf.
//   - SA5010 — невозможный type assertion.
//   - SA5011 — возможное разыменование nil.
//   - SA5012 — slice нечётной длины для функции, ожидающей чётную.
//   - SA6000 — компиляция regexp на каждой итерации цикла.
//   - SA6001 — упущенная оптимизация map lookup по byte slice.
//   - SA6002 — хранение non-pointer в sync.Pool с лишней аллокацией.
//   - SA6003 — лишнее преобразование string в []rune перед range.
//   - SA6005 — неэффективное сравнение через strings.ToLower/ToUpper.
//   - SA6006 — запись []byte через io.WriteString.
//   - SA9001 — defer в range-цикле выполняется позже ожидаемого.
//   - SA9002 — не восьмеричное значение os.FileMode, похожее на восьмеричное.
//   - SA9003 — пустое тело ветви if или else.
//   - SA9004 — явный тип указан только у первой константы группы.
//   - SA9005 — сериализация структуры без экспортируемых полей.
//   - SA9006 — подозрительный сдвиг integer фиксированного размера.
//   - SA9007 — удаление директории, которую нельзя удалять.
//   - SA9008 — else type assertion читает, вероятно, не то значение.
//   - SA9009 — неэффективная директива компилятора Go.
//
// # Другие классы Staticcheck и публичные анализаторы
//
// Дополнительно включены:
//
//   - S1000 из класса simplifications — заменяет одноветочный select более
//     простым получением из канала или отправкой в канал.
//   - bodyclose — проверяет закрытие Body у HTTP-ответов и предотвращает
//     утечки соединений и файловых дескрипторов.
//   - nilerr — обнаруживает возврат nil после проверки err != nil и возврат
//     ошибки из ветви, в которой err == nil.
//   - noosexit — собственный анализатор проекта; запрещает прямой вызов
//     os.Exit внутри функции main пакета main, потому что os.Exit пропускает
//     все отложенные вызовы. Вспомогательные функции и косвенные вызовы через
//     переменную не запрещаются.
